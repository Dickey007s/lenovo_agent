// Mechanical generation keeps file:// usable without fetching sources.json.
const fs = require("node:fs");
const path = require("node:path");
const { createRequire } = require("node:module");
const root = __dirname;
const data = JSON.parse(fs.readFileSync(path.join(root, "sources.json"), "utf8"));
fs.writeFileSync(path.join(root, "sources-data.js"), "// Generated by build.cjs from sources.json.\nwindow.COPILOT_LIBRARY = " + JSON.stringify(data).replace(/</g, "\\u003c") + ";\n", "utf8");
const requireWeb = createRequire(path.resolve(root, "../../../apps/web/package.json"));
const React = requireWeb("react");
const { renderToStaticMarkup } = requireWeb("react-dom/server");
const tabler = requireWeb("@tabler/icons-react");
const names = ["IconBooks", "IconCalendar", "IconDownload", "IconX", "IconSearch", "IconFilterOff", "IconGitBranch", "IconChecklist", "IconInfoCircle", "IconArrowRight", "IconArrowUpRight", "IconFileText", "IconFileSearch", "IconBulb", "IconFlask"];
const icons = Object.fromEntries(names.map(name => [name, renderToStaticMarkup(React.createElement(tabler[name], { size: 20, stroke: 1.65, "aria-hidden": true }))]));
fs.writeFileSync(path.join(root, "icons.js"), "// Generated from the repository's @tabler/icons-react. MIT; see TABLER-LICENSE.\nwindow.LIBRARY_ICONS = " + JSON.stringify(icons) + ";\n", "utf8");
const modulePath = path.dirname(requireWeb.resolve("@tabler/icons-react/package.json"));
fs.copyFileSync(path.join(modulePath, "LICENSE"), path.join(root, "TABLER-LICENSE"));
console.log(`Generated local data for ${data.sources.length} sources and ${names.length} Tabler icons.`);
